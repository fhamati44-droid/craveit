-- Shared TAMAM home-cooked catalog.
-- The existing Kitchen 11 menu is copied once as the initial shared product
-- list. Participating kitchens are linked through offers; their regular menus
-- and daily menus are left untouched.

create table if not exists public.home_cooked_products (
  id bigint generated by default as identity primary key,
  source_menu_item_id bigint unique references public.menu_items(id) on delete set null,
  source_category_id bigint,
  category_name text,
  category_name_ar text,
  category_name_he text,
  category_name_en text,
  name text not null,
  name_ar text,
  name_he text,
  name_en text,
  description text,
  description_ar text,
  description_he text,
  description_en text,
  image_url text,
  base_price numeric(10,2) not null default 0,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.home_cooked_kitchens (
  restaurant_id bigint primary key references public.restaurants(id) on delete cascade,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.home_cooked_offers (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.home_cooked_products(id) on delete cascade,
  restaurant_id bigint not null references public.home_cooked_kitchens(restaurant_id) on delete cascade,
  price numeric(10,2) not null check (price >= 0),
  extras_source_menu_item_id bigint references public.menu_items(id) on delete set null,
  is_available boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (product_id, restaurant_id)
);

create index if not exists home_cooked_products_active_order_idx
  on public.home_cooked_products (is_active, sort_order, id);
create index if not exists home_cooked_offers_product_available_idx
  on public.home_cooked_offers (product_id, is_available, sort_order);

-- Source restaurant 4 is the existing Kitchen 11 catalog (slug: kitchen11).
-- It seeds the shared list; it is not itself treated as a special seller.
insert into public.home_cooked_products (
  source_menu_item_id, source_category_id,
  category_name, category_name_ar, category_name_he, category_name_en,
  name, name_ar, name_he, name_en,
  description, description_ar, description_he, description_en,
  image_url, base_price, sort_order, is_active
)
select
  m.id,
  c.id,
  c.name,
  c.name_ar,
  to_jsonb(c)->>'name_he',
  to_jsonb(c)->>'name_en',
  m.name,
  m.name_ar,
  m.name_he,
  m.name_en,
  m.description,
  m.description_ar,
  m.description_he,
  m.description_en,
  m.image_url,
  m.price,
  m.sort_order,
  true
from public.menu_items m
left join public.menu_categories c on c.id = m.category_id
where m.restaurant_id = 4
  and m.active is distinct from false
  and m.is_available is distinct from false
on conflict (source_menu_item_id) do nothing;

-- Register the requested participating kitchens. These are the real seller
-- restaurant rows; the legacy Kitchen 11 source row is not exposed as a seller.
insert into public.home_cooked_kitchens (restaurant_id, sort_order)
select r.id, v.sort_order
from (values
  (1::bigint, 1),  -- Kitchen 11
  (14::bigint, 2), -- Maha
  (16::bigint, 3), -- Mariana
  (17::bigint, 4), -- Sahriyat
  (13::bigint, 5)  -- Mazawi
) as v(restaurant_id, sort_order)
join public.restaurants r on r.id = v.restaurant_id
where r.id in (1, 13, 14, 16, 17)
  and r.active is distinct from false
on conflict (restaurant_id) do nothing;

-- Start with the source prices and the same extras source. Restaurants can be
-- assigned different prices later without duplicating or renaming the dish.
insert into public.home_cooked_offers (
  product_id, restaurant_id, price, extras_source_menu_item_id, is_available, sort_order
)
select
  p.id,
  k.restaurant_id,
  p.base_price,
  case when k.restaurant_id = 1 then p.source_menu_item_id else null end,
  true,
  p.sort_order
from public.home_cooked_products p
cross join public.home_cooked_kitchens k
where p.is_active
  and k.is_active
on conflict (product_id, restaurant_id) do nothing;

alter table public.home_cooked_products enable row level security;
alter table public.home_cooked_kitchens enable row level security;
alter table public.home_cooked_offers enable row level security;

drop policy if exists "public read active home cooked products" on public.home_cooked_products;
create policy "public read active home cooked products" on public.home_cooked_products
  for select to anon, authenticated using (is_active);

drop policy if exists "public read active home cooked kitchens" on public.home_cooked_kitchens;
create policy "public read active home cooked kitchens" on public.home_cooked_kitchens
  for select to anon, authenticated using (is_active);

drop policy if exists "public read available home cooked offers" on public.home_cooked_offers;
create policy "public read available home cooked offers" on public.home_cooked_offers
  for select to anon, authenticated using (
    is_available
    and exists (
      select 1 from public.home_cooked_products p
      where p.id = home_cooked_offers.product_id and p.is_active
    )
    and exists (
      select 1 from public.home_cooked_kitchens k
      where k.restaurant_id = home_cooked_offers.restaurant_id and k.is_active
    )
  );

revoke all on public.home_cooked_products from anon, authenticated;
revoke all on public.home_cooked_kitchens from anon, authenticated;
revoke all on public.home_cooked_offers from anon, authenticated;
grant select on public.home_cooked_products to anon, authenticated;
grant select on public.home_cooked_kitchens to anon, authenticated;
grant select on public.home_cooked_offers to anon, authenticated;
